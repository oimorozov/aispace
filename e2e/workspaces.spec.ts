import { expect, test, type APIRequestContext, type Page } from '@playwright/test'

const backend = `${(process.env.AISPACE_E2E_API_URL || 'http://127.0.0.1:8000').replace(/\/$/, '')}/api`
const provider = 'http://127.0.0.1:8766'
const providerBaseUrl = process.env.AISPACE_E2E_PROVIDER_URL || `${provider}/v1`
const selector = (page: Page) => page.getByRole('combobox', { name: 'Рабочее пространство', exact: true })
const node = (page: Page, id: string) => page.locator(`.react-flow__node[data-id="${id}"]`)
const scope = (id: string) => `${backend}/workspaces/${id}`

async function createWorkspace(request: APIRequestContext, name: string) {
  const response = await request.post(`${backend}/workspaces`, { data: { name } })
  expect(response.ok()).toBeTruthy()
  return response.json()
}

async function createTasklet(request: APIRequestContext, wid: string, title: string, delay = 0.1) {
  const response = await request.post(`${scope(wid)}/tasklets`, { data: { title, prompt: `[[label:${title}]][[delay:${delay}]]`, position: { x: 100, y: 100 } } })
  expect(response.ok()).toBeTruthy()
  return response.json()
}

async function snapshot(request: APIRequestContext, wid: string) {
  const response = await request.get(scope(wid))
  expect(response.ok()).toBeTruthy()
  return response.json()
}

