test('Codex keeps separate workspace contexts, directories and threads when chats are resumed', async ({ page, request }) => {
  const a = await createWorkspace(request, 'Codex A')
  const b = await createWorkspace(request, 'Codex B')
  const root = (await (await request.get(`${backend}/directories`)).json()).path.replace(/\/$/, '')
  expect((await request.patch(`${backend}/settings`, { data: { execution_mode: 'codex', model: '', api_key: null } })).ok()).toBeTruthy()
  for (const [item, folder, context] of [[a, 'demo', 'Контекст проекта A'], [b, 'other', 'Контекст проекта B']] as const) {
    expect((await request.patch(scope(item.id), { data: { working_directory: `${root}/${folder}`, workspace_context: context } })).ok()).toBeTruthy()
  }
  const ta = await createTasklet(request, a.id, 'codex-space-a')
  const tb = await createTasklet(request, b.id, 'codex-space-b')
  expect((await request.post(`${scope(a.id)}/pipeline/start`)).ok()).toBeTruthy()
  await expect.poll(async () => (await snapshot(request, a.id)).pipeline.status).toBe('completed')
  const completedA = await snapshot(request, a.id)
  expect((await request.post(`${scope(b.id)}/pipeline/start`)).ok()).toBeTruthy()
  await expect.poll(async () => (await snapshot(request, b.id)).pipeline.status).toBe('completed')
  expect(await snapshot(request, a.id)).toEqual(completedA)
  await page.goto('/')
  await selector(page).selectOption(a.id)
  await node(page, ta.id).click()
  await page.getByRole('tab', { name: /^Чат/ }).click()
  await page.getByPlaceholder('Напишите сообщение…', { exact: true }).fill('Продолжи [[label:codex-space-a-resume]]')
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click()
  await expect(page.getByText('Готово: codex-space-a-resume.', { exact: true })).toBeVisible()
  const events = (await (await request.get(`${provider}/audit`)).json()).events.filter((event: { transport: string; kind: string }) => event.transport === 'codex' && event.kind === 'start')
  expect(events.map((event: { label: string }) => event.label)).toEqual(['codex-space-a', 'codex-space-b', 'codex-space-a-resume'])
  expect(events[0].thread_id).not.toBe(events[1].thread_id)
  expect(events[2].thread_id).toBe(events[0].thread_id)
  expect(events[0].parameters.cwd).toBe(`${root}/demo`)
  expect(events[1].parameters.cwd).toBe(`${root}/other`)
  expect(JSON.stringify(events[0])).toContain('Контекст проекта A')
  expect(JSON.stringify(events[0])).not.toContain('Контекст проекта B')
  expect(JSON.stringify(events[1])).toContain('Контекст проекта B')
  expect(JSON.stringify(events[1])).not.toContain('Контекст проекта A')
  expect((await (await request.get(`${scope(a.id)}/tasklets/${ta.id}/messages`)).json()).length).toBe(4)
  expect((await (await request.get(`${scope(b.id)}/tasklets/${tb.id}/messages`)).json()).length).toBe(2)
})

test('a delayed save preserves a newer draft entered after switching away and back', async ({ page, request }) => {
  const a = await createWorkspace(request, 'Сохранение A')
  const b = await createWorkspace(request, 'Сохранение B')
  const tasklet = await createTasklet(request, a.id, 'Редактирование')
  await page.goto('/')
  await selector(page).selectOption(a.id)
  await node(page, tasklet.id).click()
  let release: () => void = () => {}
  const gate = new Promise<void>(resolve => { release = resolve })
  let intercepted = false
  let delivered = false
  await page.route(`**/api/workspaces/${a.id}/tasklets/${tasklet.id}`, async route => {
    const response = await route.fetch()
    intercepted = true
    await gate
    await route.fulfill({ response })
    delivered = true
  })
  await page.getByRole('textbox', { name: 'Промпт', exact: true }).fill('Отправленная инструкция')
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect.poll(() => intercepted).toBe(true)
  await selector(page).selectOption(b.id)
  await selector(page).selectOption(a.id)
  await page.getByRole('textbox', { name: 'Промпт', exact: true }).fill('Более новый черновик')
  release()
  await expect.poll(() => delivered).toBe(true)
  await expect(page.getByRole('textbox', { name: 'Промпт', exact: true })).toHaveValue('Более новый черновик')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Промпт', exact: true })).toHaveValue('Более новый черновик')
  expect((await snapshot(request, a.id)).tasklets[0].prompt).toBe('Отправленная инструкция')
})

